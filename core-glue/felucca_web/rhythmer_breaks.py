"""Rhythmer's factory break banks as a C header, for core_rhythmer.c (run by core_rhythmer.cmake's generate step,
in the submodule's jiant/ folder): the two prepared slots of the device package, byte for byte as
tools/fm1pkg_make.py with_factory_banks writes them (amen-160.slot at 0xA0000, think-160.slot at 0xB4000, the
RHYBRK1 marker at 0x93000), checked the same way.
  rhythmer_breaks.py <assets/breaks dir> <out.h>"""
import struct
import sys
import zlib
from pathlib import Path


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    slots = [(src / (n + ".slot")).read_bytes() for n in ("amen-160", "think-160")]
    for slot in slots:          # fm1pkg_make.with_factory_banks' checks
        h = struct.unpack_from("<13I", slot)
        if (len(slot) != 0x14000 or slot[:7] != b"FSMP\x0c\0\1" or (h[4], h[8], h[9], h[12]) != (72000, 0, 48000, 23777)
                or zlib.crc32(slot[512:72512]) != h[5]):
            raise SystemExit("rhythmer_breaks: an invalid PCM12 bank")
    marker = b"RHYBRK1\0" + struct.pack("<IIIII", 1, 0xA0000, 0xC8000, 0x14000, 2)
    marker += struct.pack("<I", zlib.crc32(marker))
    lines = ["/* generated by core-glue/felucca_web/rhythmer_breaks.py from Rhythmer's assets/breaks: the device",
             " * package's factory banks (fm1pkg_make.with_factory_banks). Not under the GPL: THIRD-PARTY-AUDIO.txt */",
             "#define RHY_BRK_AT 0xA0000u", "#define RHY_BRK_SLOT 0x14000u", "#define RHY_BRK_MARK_AT 0x93000u"]

    def arr(name, b):
        lines.append(f"static const uint8_t {name}[{len(b)}] = {{")
        for i in range(0, len(b), 32):
            lines.append("    " + ",".join(str(x) for x in b[i:i + 32]) + ",")
        lines.append("};")
    arr("RHY_BRK_MARK", marker)
    arr("RHY_BRK0", slots[0])
    arr("RHY_BRK1", slots[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
