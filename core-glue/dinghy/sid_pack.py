"""The sid core's tune pack (core_sid.cmake, at configure time): FM-1 SID's own tools/sidpack.py pack() of the
given songs, as a C array for sid_host.c's _pack (on the device the pack follows the image in flash):
    sid_pack.py FM1SID_TOOLS_DIR OUT.h TUNE[:SONG] ...
Written only when it changed (no needless rebuild)."""
import sys
from pathlib import Path

tools, out, tunes = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3:]
sys.path.insert(0, str(tools))
import sidpack  # noqa: E402  (fm1-sid/tools/sidpack.py, BSD-2-Clause)

items = []
for t in tunes:
    path, _, song = t.partition(":")
    items.append((Path(path).read_bytes(), int(song) if song else 0))
pack = sidpack.pack(items, 0, 0)
rows = [",".join(str(b) for b in pack[i:i + 32]) for i in range(0, len(pack), 32)]
text = ("/* generated by core-glue/dinghy/sid_pack.py: fm1-sid tools/sidpack.py pack() of\n * "
        + "\n * ".join(Path(t.partition(":")[0]).name for t in tunes) + " */\n"
        + f"static const uint8_t fm1core_sid_pack[{len(pack)}] __attribute__((aligned(4))) = {{\n"
        + ",\n".join(rows) + "};\n")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
print(f"{out}: {len(tunes)} tunes, {len(pack)} bytes")
