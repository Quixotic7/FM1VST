"""rfm1_labels: a firmware's RemoteFM1Metadata.json "labels" (docs/RFM1-METADATA.md) as the C header the .rfm1's
core-glue/common/rfm1_shim.c is compiled with (fm1_add_rfm1, cmake/FM1Rfm1.cmake). Python 3 standard library only.

    rfm1_labels.py header --metadata <repo>/RemoteFM1Metadata.json --out rfm1_meta_labels.h [--id <id>]
                   [--no-json-warning]

labels.buttons (by printed name: FX SEL ENV LFO EDIT GLO HOME SAVE ARP SEQ PLAY REC OCT- OCT+, any case) replace the
descriptor's button_names for those buttons; labels.knobs (SELECT ALGO PRESETS K1 K2 K3 K4 MASTER) and the buttons
are also the static live labels (docs/DYNAMIC-LABELS.md slots 0..7, 8..21) served while the core has none of its own.
A label: 0..10 characters, upper case, printable ASCII; "" = no job. A bad entry is skipped with a warning; nothing
here fails the build. The header always gets written (RFM1_META_LABELS 0 when there is nothing to use).
"""
import argparse
import json
import os
import re
import sys

BUTTONS = ("FX", "SEL", "ENV", "LFO", "EDIT", "GLO", "HOME", "SAVE", "ARP", "SEQ", "PLAY", "REC", "OCT-", "OCT+")
KNOBS = ("SELECT", "ALGO", "PRESETS", "K1", "K2", "K3", "K4", "MASTER")
LBL_KNOB0, LBL_BTN0, LBL_N, LBL_MAX = 0, 8, 49, 10
TAG = "rfm1-meta-labels:"                 # in the module's data: rfm1_check reports the counts from it
LABEL_RE = re.compile(r"[\x20-\x7E]{0,%d}" % LBL_MAX)


def label_problem(v):
    if not isinstance(v, str):
        return "not a string"
    if len(v) > LBL_MAX:
        return "%d characters (at most %d)" % (len(v), LBL_MAX)
    if not LABEL_RE.fullmatch(v):
        return "not printable ASCII"
    if v != v.upper():
        return "not upper case"
    return None


def from_metadata(path, warn, json_warn=True):
    """{"buttons": {index: label}, "knobs": {index: label}} or None; every problem to warn() (a file that is not JSON:
    only with json_warn, so that a build reading its skin too says it once)"""
    try:
        with open(path, "rb") as f:
            m = json.loads(f.read().decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as e:
        if json_warn:
            warn("not valid JSON, ignored (%s)" % e)
        return None
    if not isinstance(m, dict) or "labels" not in m:
        return None
    lb = m["labels"]
    if not isinstance(lb, dict):
        warn("labels: not an object, ignored")
        return None
    out = {"buttons": {}, "knobs": {}}
    for k in lb:
        if k not in ("buttons", "knobs"):
            warn("labels: unknown field %r ignored" % k)
    for part, names in (("buttons", BUTTONS), ("knobs", KNOBS)):
        if part not in lb:
            continue
        t = lb[part]
        if not isinstance(t, dict):
            warn("labels.%s: not an object, ignored" % part)
            continue
        for k, v in t.items():
            key = k.upper() if isinstance(k, str) else k
            if key not in names:
                warn("labels.%s: unknown %s %r skipped (%s)" % (part, part[:-1], k, " ".join(names)))
                continue
            why = label_problem(v)
            if why:
                warn("labels.%s.%s: %r is %s: skipped" % (part, k, v, why))
                continue
            out[part][names.index(key)] = v
    if not out["buttons"] and not out["knobs"]:
        if lb:
            warn("labels: nothing usable")
        return None
    return out


def c_str(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(lb, source=""):
    lines = ["/* generated by tools/rfm1_labels.py from %s: do not edit */" % (source or "nothing"),
             "#pragma once"]
    if not lb:
        lines.append("#define RFM1_META_LABELS 0")
        return "\n".join(lines) + "\n"
    btn = ["NULL"] * len(BUTTONS)
    slot = ["NULL"] * LBL_N
    for i, v in lb["buttons"].items():
        btn[i] = slot[LBL_BTN0 + i] = c_str(v)
    for i, v in lb["knobs"].items():
        slot[LBL_KNOB0 + i] = c_str(v)
    lines += ["#define RFM1_META_LABELS 1",
              "#define RFM1_META_TAG \"%sb=%d,k=%d\"" % (TAG, len(lb["buttons"]), len(lb["knobs"])),
              "static const char *const RFM1_META_BTN[FM1P_NB] = {%s};" % ", ".join(btn),
              "static const char *const RFM1_META_SLOT[FM1CORE_LBL_N] = {",
              "    " + ", ".join(slot), "};"]
    return "\n".join(lines) + "\n"


def summary(module_bytes):
    """"N buttons, M knobs" from an .rfm1's data (the tag), or "" """
    at = module_bytes.find(TAG.encode())
    if at < 0:
        return ""
    m = re.match(rb"b=(\d+),k=(\d+)", module_bytes[at + len(TAG):at + len(TAG) + 16])
    return "%d buttons, %d knobs" % (int(m.group(1)), int(m.group(2))) if m else ""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    h = sub.add_parser("header")
    h.add_argument("--metadata", required=True)
    h.add_argument("--out", required=True)
    h.add_argument("--id", default="")
    h.add_argument("--no-json-warning", action="store_true", help="say nothing of a file that is not JSON")
    a = ap.parse_args()

    def warn(m):
        print("rfm1_labels: warning: %s%s: %s" % (a.id + ": " if a.id else "", a.metadata, m), file=sys.stderr)
    try:
        lb = from_metadata(a.metadata, warn, not a.no_json_warning)
    except Exception as e:                     # (never fail the build on the author's file)
        warn("unreadable, no labels (%s)" % e)
        lb = None
    text = header(lb, os.path.basename(a.metadata))
    tmp = a.out + ".tmp"
    with open(tmp, "w", encoding="ascii") as f:
        f.write(text)
    os.replace(tmp, a.out)
    if lb:
        print("rfm1_labels: %s%d buttons, %d knobs" % (a.id + ": " if a.id else "", len(lb["buttons"]),
                                                      len(lb["knobs"])))


if __name__ == "__main__":
    main()
