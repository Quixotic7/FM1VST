static const uint8_t TKD_COLON[5] = {0x00, 0x36, 0x36, 0x00, 0x00};
static const uint8_t TKD_BLANK[5] = {0, 0, 0, 0, 0};

static inline const uint8_t *tkd_glyph(char c)
{
    if (c >= '0' && c <= '9') return TKD_DIGITS[c - '0'];
    if (c >= 'A' && c <= 'Z') return TKD_LETTERS[c - 'A'];
    if (c >= 'a' && c <= 'z') return TKD_LETTERS[c - 'a'];
    if (c == '+') return TKD_PLUS;
    if (c == '-') return TKD_MINUS;
    if (c == ':') return TKD_COLON;
    return TKD_BLANK;
}

/* a decimal into s (at most 11 characters and the NUL); the end */
static inline char *tkd_num(char *s, long v)
{
    char t[12];
    int n = 0;
    unsigned long u = v < 0 ? (unsigned long)-v : (unsigned long)v;
    if (v < 0)
        *s++ = '-';
    do {
        t[n++] = (char)('0' + u % 10u);
        u /= 10u;
    } while (u && n < 11);
    while (n)
        *s++ = t[--n];
    *s = 0;
    return s;
}
static inline char *tkd_cat(char *s, const char *a)
{
    while (*a)
        *s++ = *a++;
    *s = 0;
    return s;
}
